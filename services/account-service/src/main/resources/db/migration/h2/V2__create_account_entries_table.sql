CREATE TABLE account_entries (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    account_id      BIGINT,
    transfer_id     BIGINT,
    type            VARCHAR(20)   NOT NULL,
    amount          NUMERIC(38, 4),
    balance_after   NUMERIC(38, 4),
    created_at      TIMESTAMP(6),
    CONSTRAINT ck_accounts_entries_type CHECK (type IN ('DEPOSIT', 'DEBIT', 'CREDIT')),
    CONSTRAINT fk_account_account_entries
        FOREIGN KEY (account_id)
            REFERENCES accounts (id)
            ON DELETE SET NULL
)